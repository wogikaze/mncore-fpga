#!/usr/bin/env python3
"""Regenerate the assemble3 outputs used by the unit tests (needs WSL + assemble3).

    python mncore/tools/mnisa/tests/make_fixtures.py

For every tests/data/<name>.vsm it writes <name>.asm and <name>.csv (flat, packer disabled,
'd' and 'r' lines kept). imm_probe.vsm is generated here from IMM_VALUES.
"""
from __future__ import annotations

import shutil
import sys
import tempfile
from pathlib import Path

HERE = Path(__file__).resolve().parent
DATA = HERE / "data"
sys.path.insert(0, str(HERE.parents[1]))

from mnisa import assembler  # noqa: E402

# (literal, payload) pairs: every single bit plus a few patterns.
IMM_VALUES = [(f'i"{1 << k}"', 1 << k) for k in range(31)] + [
    ('ui"0x80000000"', 0x80000000), ('i"-1"', 0xFFFFFFFF), ('i"0x12345678"', 0x12345678),
    ('ui"0xdeadbeef"', 0xDEADBEEF), ('ui"0x0f0f0f0f"', 0x0F0F0F0F), ('f"1.0"', 0x3F800000),
]


def main() -> int:
    lines = ["# generated by make_fixtures.py: imm <literal> $lr0, one per line"]
    lines += [f"imm {lit} $lr0" for lit, _ in IMM_VALUES]
    (DATA / "imm_probe.vsm").write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    sources = {p.stem: p.read_text(encoding="utf-8") for p in sorted(DATA.glob("*.vsm"))}
    with tempfile.TemporaryDirectory() as tmp:
        out = assembler.assemble_sources(sources, tmp, keep_data=True)
        for name in sources:
            rc = (out / f"{name}.flat.rc").read_text().strip()
            if rc != "0":
                print(f"{name}.vsm: assemble3 failed:\n" + (out / f"{name}.flat.err").read_text(errors="replace"))
                return 1
            shutil.copyfile(out / f"{name}.flat.asm", DATA / f"{name}.asm")
            shutil.copyfile(out / f"{name}.flat.csv", DATA / f"{name}.csv")
            print(f"wrote {name}.asm / {name}.csv")
        (DATA / "ASSEMBLER_VERSION").write_text((out / "VERSION").read_text(), encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
