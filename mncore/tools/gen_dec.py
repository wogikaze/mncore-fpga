# ---------------------------------------------------------------------------------------------
# Issue-group flags of a j word ("which instruction expressions were issued together").
# Each flag is gated by exec (ll = 01 or 11), except WAIT, which is gated by ll != 10: assemble3
# encodes 'nop ; wait i01' as ll = 00 with wd = 01 (wait is the only expression it accepts next to
# nop). The Python model of the same flags is in mncore/sim/tb/dec/gen_vectors.py (ref_groups) and
# is written separately on purpose.
# Grounding (assemble3 probes + corpus, see mncore/status/WP-10.md):
#   - nop word: aluc dmode=11 aluop=00000 isela=1000 iselb=111; mauc isel a/b/c=111; l1bm_isel=111;
#     l2bm_dmode=11; rfc0 wwl=rwl=01, rfc1 wwl=01; everything else 0.
#   - ALU: every corpus word without an ALU expression has (dmode, aluop) = (11, 00000); no such
#     word writes an ALU result (isel=01 with write, or $omr with ifsel=0).
#   - MAU: no word with enfma=0 writes a MAU result (isel=00 with write, or $omr with ifsel=1).
#   - L1BM: l1bm_me=0 also occurs with L1BM expressions that use the turnaround register $lbi
#     (l1bmm4@1 $lr0 $lbi), so the flag is "any L1BM field differs from the nop word, or a PE
#     write takes L1BM data (isel=10)". l1bm_gwrite / l1bm_gadr belong to the L2BM expression.
#   - L2BM: every corpus word with gwrite = lwrite = darsend = darwrite = 0 has all L2BM fields at
#     the nop values.
#   - $mb / $nb: write=1, maadj=0, madpe=11 ($lmb gives wl=01, $mb wl=00). In imm words the LM0
#     fields carry the payload, so LM0 is not written.
#   - Matrix read (?mread) has no field of its own (gmread $ly0 $nowrite differs from nop only in
#     ll and mauc_dmode), so there is no flag for it.
GROUPS = [
    ("ALU", "ALU expression (imm included)", "!(pe_aluc_dmode == 2'b11 && pe_aluc_aluop == 5'b00000)"),
    ("IMM", "imm / immu (aluop = 11111)", "is_imm"),
    ("MAU", "MAU arithmetic (enfma)", "pe_mauc_enfma"),
    ("MW", "matrix register write (?mwrite)", "pe_mauc_mw"),
    ("L1BM", "L1BM expression (PE <-> L1BM, $lbi)", "l1bm_any"),
    ("L2BM", "L2BM expression (L1BM <-> L2BM, DAR)", "l1bm_gwrite | l2bm_lwrite | l2bm_darsend | l2bm_darwrite"),
    ("WAIT", "wait for MV tag wd", "wd != 8'd0"),
    ("WR_T", "write T", "pe_trc_write"),
    ("WR_GRF0", "write GRF0", "pe_rfc0_write"),
    ("WR_GRF1", "write GRF1", "pe_rfc1_write"),
    ("WR_LM0", "write LM0 (not in imm words, not $mb)", "pe_lm0_write & !is_imm & !lm0_base"),
    ("WR_LM1", "write LM1 (not $nb)", "pe_lm1_write & !lm1_base"),
    ("WR_MB", "write the LM0 base register $mb / $lmb", "pe_lm0_write & !is_imm & lm0_base"),
    ("WR_NB", "write the LM1 base register $nb / $lnb", "pe_lm1_write & lm1_base"),
    ("WR_OMR", "write a mask register $omr<n>", "pe_mrc_omr != 4'd0"),
]
GROUP_NAMES = [g[0] for g in GROUPS]

# Fields of the L1BM expression and their values in the nop word (l1bm_gwrite / gadr excluded).
L1BM_NOP = {
    "l1bm_bmode": 0, "l1bm_lwrite": 0, "l1bm_rmode": 0, "l1bm_me": 0, "l1bm_ladr": 0, "l1bm_dmode": 0,
    "l1bm_ext": 0, "l1bm_round_out": 0, "l1bm_mabadr": 0, "l1bm_opcode": 0, "l1bm_isel": 7, "l1bm_wl": 0,
}

ERR_CODES = [("MN_DEC_OK", 0, "no error"), ("MN_DEC_E_DECODE", 1, "ll = 10 (the emulator stops)"),
             ("MN_DEC_E_UNSUPPORTED", 2, "a field value the decoder does not know (err_field names it)")]

SLOT_J = 16  # j fields are at most 13 bits
SLOT_M = 32  # m fields are at most 30 bits (adra)


def jschema():
    return _schema.load("j")


def mschema():
    return _schema.load("m")


def mport(name: str) -> str:
    """Verilog port name of an m field ('priority' is an SV keyword, so every m port gets 'mv_')."""
    return "mv_" + name


def idx_width(n: int) -> int:
    return max(1, (n - 1).bit_length())


def msb_lsb(width_word: int, f) -> tuple[int, int]:
    return width_word - 1 - f.pos, width_word - 1 - (f.pos + f.width - 1)


# ---------------------------------------------------------------------------------------------
# Unsupported checks (one flag per field). Shared by the RTL generator; the reference model in
# gen_vectors.py recomputes them with mnisa.schema (enum_applies / enum_name).
#   j: ll = 10 -> E_DECODE. When exec (ll = 01 / 11): rsv_* != 0, and every enum field whose
#      table does not list all 2^width values, where the enum applies (not an imm payload field in
#      an imm word; enum_when holds) -> E_UNSUPPORTED <field>. ll = 00 words are nops and are not
#      checked (the emulator ignores their other fields).
#   m: when valid = 1, the same enum rule.

def unsup_checks(kind: str) -> list[dict]:
    s = jschema() if kind == "j" else mschema()
    out = []
    imm_fields = s.imm_fields() if kind == "j" else frozenset()
    for f in s.fields:
        port = f.name if kind == "j" else mport(f.name)
        if kind == "j" and f.name == "ll":
            out.append(dict(field=f, cond="ll == 2'b10", gates=[], why="ll = 10 (invalid, E_DECODE)"))
            continue
        if f.group == "rsv":
            out.append(dict(field=f, cond=f"{port} != {f.width}'d0", gates=["exec"], why="reserved field not 0"))
            continue
        if not f.enum:
            continue
        valid = sorted(int(e.val, 2) for e in f.enum)
        if len(valid) == 1 << f.width:
            continue
        missing = [v for v in range(1 << f.width) if v not in valid]
        cond = " || ".join(f"{port} == {f.width}'b{v:0{f.width}b}" for v in missing)
        gates = ["exec"] if kind == "j" else [mport("valid")]
        why = "value not in the enum table: " + ", ".join(f"{v:0{f.width}b}" for v in missing)
        if f.name in imm_fields:
            gates.append("!is_imm")
            why += " (not checked in imm words: payload)"
        if f.enum_when:
            g = s.by_name[f.enum_when[0]]
            gp = g.name if kind == "j" else mport(g.name)
            gates.append(f"{gp} == {g.width}'b{f.enum_when[1]}")
            why += f" (only when {g.name} = {f.enum_when[1]})"
        out.append(dict(field=f, cond=cond, gates=gates, why=why))
    return out


