#!/usr/bin/env python3
"""Generate the RTL instruction decoders from mncore/spec/isa/*.yaml (WP10).

    python mncore/tools/gen_dec.py            write the generated files
    python mncore/tools/gen_dec.py --check    exit 1 if a committed file differs from the generator output

Generated files (commit them; the test runs --check):
    mncore/rtl/dec/mn_jfields.vh        j word (426 bit): localparams, slice macros, enum values, group indices
    mncore/rtl/dec/mn_mfields.vh        m word (82 bit): the same
    mncore/rtl/dec/mn_dec_j.v           426 bit -> one port per field + derived signals
    mncore/rtl/dec/mn_dec_m.v           82 bit -> one port per field (prefix mv_) + derived signals
    mncore/sim/tb/dec/tb_dec.v          self-checking testbench (vectors from mncore/sim/tb/dec/gen_vectors.py)
    mncore/sim/tb/dec/mn_dec_harness.v  registered wrapper of both decoders: the lint / synth top

Field positions, cycle1..3 address fields and the immediate layout come from the YAML only. The
derived logic that the YAML does not describe (issue-group flags, unsupported checks) is written
here in Verilog; the testbench compares it with an independent Python model (gen_vectors.py) that
takes mnisa (WP01) as the reference.

Vector layout (shared with gen_vectors.py through j_items() / m_items()): one line per word,
'<word bits>_<expected>' for $readmemb, the word first (pos 0 = leftmost = MSB). The expected part
is the list of items below, each zero-extended to its slot width, first item leftmost.
"""
