# Vector layout: (label, verilog expression of the DUT output, width, slot)

def j_items() -> list[tuple[str, str, int, int]]:
    s = jschema()
    items = [(f.name, f.name, f.width, SLOT_J) for f in s.fields]
    items += [("exec", "exec", 1, 1), ("nop", "nop", 1, 1), ("noforward", "noforward", 1, 1)]
    for key, names in s.cycle_addr.items():
        w = s[names[0]].width
        for c in range(4):
            items.append((f"cyc_{key}[{c}]", f"cyc_{key}[{w * c + w - 1}:{w * c}]", w, SLOT_J))
    items += [("is_imm", "is_imm", 1, 1), ("imm32", "imm32", 32, 32)]
    for k, g in enumerate(GROUP_NAMES):
        items.append((f"grp.{g}", f"grp[{k}]", 1, 1))
    nf = len(s.fields)
    items += [("err_kind", "err_kind", 2, 2), ("err_field", "err_field", idx_width(nf), idx_width(nf)),
              ("unsup_vec", "unsup_vec", nf, nf)]
    return items


def m_items() -> list[tuple[str, str, int, int]]:
    s = mschema()
    items = [(f.name, mport(f.name), f.width, SLOT_M) for f in s.fields]
    nf = len(s.fields)
    items += [("err_kind", "mv_err_kind", 2, 2), ("err_field", "mv_err_field", idx_width(nf), idx_width(nf)),
              ("unsup_vec", "mv_unsup_vec", nf, nf)]
    return items


def exp_width(items) -> int:
    return sum(i[3] for i in items)


